def _cross_cov_stats(X, Xt):
    """Mean |diagonal| and mean |off-diagonal| of the empirical Cov(X, X_tilde) block."""
    X = np.asarray(X); Xt = np.asarray(Xt)
    Xc = X - X.mean(axis=0, keepdims=True)
    Tc = Xt - Xt.mean(axis=0, keepdims=True)
    C = (Xc.T @ Tc) / max(X.shape[0] - 1, 1)
    diag = float(np.abs(np.diag(C)).mean())
    n_off = max(C.size - C.shape[0], 1)
    off = float((np.abs(C).sum() - np.abs(np.diag(C)).sum()) / n_off)
    return diag, off


