"""
DiffKnock: diffusion-based model-X knockoffs.

Knockoffs are generated by noising each observed row forward to an intermediate
level t* and running a learned reverse diffusion back from there, so that each
knockoff stays coupled to its own observation.  Setting t* to None (or to the
full chain length) recovers unconditional sampling, for which the coupling
Cov(X, X_tilde) vanishes.

Feature importance is measured on a DeepLINK-style network by either a
gradient-based or a filter-based statistic, both antisymmetric, and features are
selected by the knockoff+ threshold.

Typical use:

    dk = DiffKnock(input_dim=p)
    dk.train_diffusion_for_knockoffs(X, n_epochs=600)
    Xt = dk.generate_knockoffs(X, t_star=400)
    # ... fit a DeepLINK model on (X, Xt, y), then
    W  = dk.compute_deeplink_statistics(model)
    S  = dk.select_features(W, fdr_threshold=0.2)

or end to end via DiffusionXKnockoff(input_dim=p).run(X, y, t_star=400).
"""

